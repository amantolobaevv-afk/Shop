CREATE TABLE IF NOT EXISTS aman_shop.products (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, category TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 material TEXT NOT NULL DEFAULT '', price INTEGER NOT NULL CHECK(price>0),
 images JSONB NOT NULL, active BOOLEAN NOT NULL DEFAULT true, demo BOOLEAN NOT NULL DEFAULT false,
 version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS aman_shop.variants (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INTEGER NOT NULL REFERENCES aman_shop.products(id),
 color TEXT NOT NULL, size TEXT NOT NULL, stock INTEGER NOT NULL CHECK(stock>=0),
 enabled BOOLEAN NOT NULL DEFAULT true, UNIQUE(product_id,color,size)
);
CREATE TABLE IF NOT EXISTS aman_shop.orders (
 id TEXT PRIMARY KEY, request_key TEXT NOT NULL UNIQUE, payload_hash TEXT NOT NULL,
 access_hash TEXT NOT NULL, access_token TEXT NOT NULL,
 customer TEXT NOT NULL, phone TEXT NOT NULL, address TEXT NOT NULL, note TEXT NOT NULL,
 total BIGINT NOT NULL CHECK(total>0),
 status TEXT NOT NULL CHECK(status IN ('pending','confirmed','completed','cancelled','expired')),
 payment_status TEXT NOT NULL DEFAULT 'unpaid' CHECK(payment_status='unpaid'),
 created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS aman_shop.order_items (
 order_id TEXT NOT NULL REFERENCES aman_shop.orders(id),
 variant_id INTEGER NOT NULL REFERENCES aman_shop.variants(id),
 name TEXT NOT NULL,color TEXT NOT NULL,size TEXT NOT NULL,
 price INTEGER NOT NULL CHECK(price>0),qty INTEGER NOT NULL CHECK(qty>0)
);
CREATE TABLE IF NOT EXISTS aman_shop.sessions (
 hash TEXT PRIMARY KEY,csrf TEXT NOT NULL,expires_at BIGINT NOT NULL,credential_tag TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS aman_shop.rate_limits (
 key TEXT PRIMARY KEY,count INTEGER NOT NULL,expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS aman_shop.write_lock(id INTEGER PRIMARY KEY CHECK(id=1));
INSERT INTO aman_shop.write_lock(id) VALUES(1) ON CONFLICT DO NOTHING;
CREATE INDEX IF NOT EXISTS orders_created ON aman_shop.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS orders_expiry ON aman_shop.orders(expires_at) WHERE status='pending';
CREATE INDEX IF NOT EXISTS variants_product ON aman_shop.variants(product_id);
CREATE INDEX IF NOT EXISTS sessions_expiry ON aman_shop.sessions(expires_at);
